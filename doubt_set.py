class Circle:
    def area(self, radius):
        print(f"the area of circle is: {3.14 * radius * radius}")

class Square:
    def area(self, squa):
        print(f"the side of square is: {squa * squa}")

class Rectangle:
    def area(self, length, width):
        print(f"the area of rectange is: {length * width}")

cir = Circle()
cir.area(2)
sq = Square()
sq.area(2)
rc = Rectangle()
rc.area(10, 15)

